"""## 6. Generate the 3D mesh
**T4 preset:** `balanced` (30 steps and 300 octree resolution). Switch to `high` for more detail if memory permits. A 3D model cannot be recovered perfectly from one photograph; choose a good image first.
"""

from datetime import datetime, timezone
from pathlib import Path
import torch, time, gc
import trimesh

QUALITY = 'balanced'      # 'balanced' or 'high'
SEED = 12345
PRESETS = {
    'balanced': {'num_inference_steps': 30, 'octree_resolution': 300, 'num_chunks': 12000},
    'high':     {'num_inference_steps': 50, 'octree_resolution': 380, 'num_chunks': 12000},
}
params = PRESETS[QUALITY]

RUN_ID = datetime.now(timezone.utc).strftime('%Y%m%d_%H%M%S')
RUN_DIR = OUTPUTS / f'{ASSET_NAME}_{RUN_ID}'
RUN_DIR.mkdir(parents=True, exist_ok=True)

torch.cuda.empty_cache()
start = time.perf_counter()
print('Generating:', ASSET_NAME, '| quality:', QUALITY, '| settings:', params)
try:
    with torch.inference_mode():
        shapes = pipeline(
            image=prepared_rgba,
            generator=torch.manual_seed(SEED),
            output_type='trimesh',
            **params,
        )
except torch.cuda.OutOfMemoryError as exc:
    torch.cuda.empty_cache()
    raise RuntimeError('GPU ran out of memory. Rerun this cell with QUALITY="balanced"; '
                       'close other GPU models and restart only if necessary.') from exc

mesh_raw = shapes[0]
if not isinstance(mesh_raw, trimesh.Trimesh):
    raise TypeError(f'Expected trimesh.Trimesh, got {type(mesh_raw)!r}')
if len(mesh_raw.vertices) == 0 or len(mesh_raw.faces) == 0:
    raise ValueError('The model returned an empty mesh. Try another image.')

RAW_PATH = RUN_DIR/'model_raw.glb'
mesh_raw.export(RAW_PATH)
GENERATION_SECONDS = time.perf_counter() - start
print('Success! Vertices:', len(mesh_raw.vertices), '| Faces:', len(mesh_raw.faces))
print('Time: %.1f sec' % GENERATION_SECONDS)
print('Raw geometry:', RAW_PATH)

"""## 7. Inspect geometry before changing it
Display mesh diagnostics rather than equating face count with quality. If the handle or rim is missing, **return to the photo or try another seed**. Smoothing and textures cannot reconstruct missing geometry.
"""

import numpy as np

extents = mesh_raw.bounding_box.extents
components = mesh_raw.split(only_watertight=False)
print('Vertices:', len(mesh_raw.vertices))
print('Triangles:', len(mesh_raw.faces))
print('Bounds (x,y,z):', np.round(extents, 3).tolist())
print('Connected components:', len(components))
print('Watertight:', mesh_raw.is_watertight)
print('Valid geometry:', bool(mesh_raw.is_volume) if mesh_raw.is_watertight else 'not a closed volume')
print('Nonfinite vertices:', int((~np.isfinite(mesh_raw.vertices)).any(axis=1).sum()))

"""## 8. Normalize and ground the asset for React/Three.js
The viewer is Y-up. The mesh is centered on its **horizontal** axes and raised so its lowest vertex rests at **y = 0**. Rotation is an artistic adjustment, not a mesh-quality fix.

Set `ROTATION_X_DEG = 90` or `-90` only if your model's up-axis needs it; keep zero unless preview proves otherwise.
"""

import trimesh, numpy as np
from scipy.spatial.transform import Rotation

ROTATION_X_DEG = 0.0
ROTATION_Y_DEG = 0.0
ROTATION_Z_DEG = 0.0
NORMALIZED_MAX_SIZE = 3.0

mesh_final = mesh_raw.copy()
if not np.isfinite(mesh_final.vertices).all():
    raise ValueError('Mesh has invalid vertex coordinates.')

# Optional orientation adjustment, without changing topology.
rotation = Rotation.from_euler('xyz', [ROTATION_X_DEG, ROTATION_Y_DEG, ROTATION_Z_DEG], degrees=True)
mesh_final.apply_transform(np.block([
    [rotation.as_matrix(), np.zeros((3, 1))],
    [np.zeros((1, 3)), np.ones((1, 1))]
]))

bounds = mesh_final.bounds
mesh_final.apply_translation(-mesh_final.bounding_box.centroid)
max_extent = float(mesh_final.bounding_box.extents.max())
if max_extent <= 1e-8:
    raise ValueError('Mesh bounds are degenerate.')
mesh_final.apply_scale(NORMALIZED_MAX_SIZE / max_extent)
mesh_final.apply_translation([0, -float(mesh_final.bounds[0,1]), 0])

print('Normalized geometry:', mesh_final.bounding_box.extents.round(3).tolist())
print('Ground position:', round(float(mesh_final.bounds[0,1]), 6))

"""## 9. Apply a simple PBR material (not an AI texture)
Hunyuan3D-2mini is a **shape** model. It does not generate the painted/UV textures of Hunyuan3D-Paint. We create a solid, soft material so the asset displays more naturally in Three.js. You can change `MATERIAL_HEX` (e.g. red cup `#B81830`, porcelain `#F3F1EC`).
"""

from trimesh.visual.material import PBRMaterial
from trimesh.visual import TextureVisuals

MATERIAL_HEX = '#C8283F'       # e.g. red ceramic cup; edit for other objects
METALLIC = 0.02
ROUGHNESS = 0.32

def rgba_from_hex(value):
    value = value.lstrip('#')
    if len(value) != 6:
        raise ValueError('Use a six-digit hex color such as #C8283F')
    return [int(value[i:i+2], 16) for i in (0, 2, 4)] + [255]

mesh_final.visual = TextureVisuals(material=PBRMaterial(
    baseColorFactor=rgba_from_hex(MATERIAL_HEX),
    metallicFactor=METALLIC,
    roughnessFactor=ROUGHNESS,
    doubleSided=True,
))
print('PBR material applied:', MATERIAL_HEX, '| metallic:', METALLIC, '| roughness:', ROUGHNESS)

"""## 10. Interactive 3D preview (no frontend needed)
This is a **geometry preview** with plotly. It draws up to 20,000 sampled triangles, so the downloadable mesh retains its original resolution. Inspect the handle, bottom, top, and back by rotating the preview.
"""

import plotly.graph_objects as go
import numpy as np
from IPython.display import display

MAX_PREVIEW_FACES = 20000
faces = np.asarray(mesh_final.faces)
if len(faces) > MAX_PREVIEW_FACES:
    selection = np.linspace(0, len(faces)-1, MAX_PREVIEW_FACES, dtype=int)
    faces = faces[selection]
# Remap to a compact vertex array for a lighter notebook/browser display.
unique, inverse = np.unique(faces.ravel(), return_inverse=True)
compact_v = np.asarray(mesh_final.vertices)[unique]
compact_f = inverse.reshape(-1, 3)

fig = go.Figure(data=[go.Mesh3d(
    x=compact_v[:,0], y=compact_v[:,1], z=compact_v[:,2],
    i=compact_f[:,0], j=compact_f[:,1], k=compact_f[:,2],
    color=MATERIAL_HEX, opacity=1.0, flatshading=False,
    lighting={'ambient':0.55, 'diffuse':0.8, 'specular':0.4, 'roughness':0.5},
    lightposition={'x':4,'y':8,'z':5},
)])
fig.update_layout(
    title=f'PolyGen | {ASSET_NAME} | {QUALITY}',
    scene={'aspectmode':'data','xaxis':{'visible':False},'yaxis':{'visible':False},'zaxis':{'visible':False},
           'camera':{'eye':{'x':1.9,'y':1.25,'z':1.9},'up':{'x':0,'y':1,'z':0}}},
    margin={'l':0,'r':0,'t':45,'b':0},
    height=600,
)
fig.show()
PREVIEW_PATH = RUN_DIR/'interactive_preview.html'
fig.write_html(str(PREVIEW_PATH), include_plotlyjs=True, full_html=True)
print('Preview saved:', PREVIEW_PATH)

