"""## 4. Remove background; inspect the object mask
- Alpha must contain the **entire object** (including handles / thin edges).
- If removal damages the object, rerun with `REMOVE_BACKGROUND = False` on an image that already has transparency.
- `FOREGROUND_FRACTION` controls object size inside the square: use ~0.80–0.88; avoid chopping off rims and handles.
"""

from PIL import Image, ImageOps
from rembg import remove, new_session
from IPython.display import display
import numpy as np

REMOVE_BACKGROUND = True
FOREGROUND_FRACTION = 0.82       # between 0.65 and 0.93
TARGET_SIZE = 512

raw = Image.open(INPUTS / 'reference_image.png').convert('RGBA')
original_alpha = np.asarray(raw.getchannel('A'))
transparent_source = bool((original_alpha < 250).any())

if transparent_source:
    isolated = raw
    print('Existing transparency detected; retaining original alpha.')
elif REMOVE_BACKGROUND:
    print('Removing background with isnet-general-use (first use downloads its ONNX weights)...')
    session = new_session('isnet-general-use')
    isolated = remove(raw, session=session).convert('RGBA')
else:
    raise RuntimeError('Source has no transparency. Enable REMOVE_BACKGROUND or upload a PNG with transparent background.')

alpha = np.asarray(isolated.getchannel('A'))
ys, xs = np.where(alpha > 16)
if len(xs) < 250:
    raise ValueError('Object mask is empty or unusable. Check reference image or background removal.')

# Crop exactly to the visible object, preserving thin handles, and letterbox to square.
bbox = (int(xs.min()), int(ys.min()), int(xs.max()) + 1, int(ys.max()) + 1)
cropped = isolated.crop(bbox)
content_target = int(TARGET_SIZE * FOREGROUND_FRACTION)
scale = min(content_target / cropped.width, content_target / cropped.height)
newsize = (max(1, round(cropped.width * scale)), max(1, round(cropped.height * scale)))
object_layer = cropped.resize(newsize, Image.Resampling.LANCZOS)
prepared_rgba = Image.new('RGBA', (TARGET_SIZE, TARGET_SIZE), (0, 0, 0, 0))
prepared_rgba.alpha_composite(object_layer, ((TARGET_SIZE-newsize[0])//2, (TARGET_SIZE-newsize[1])//2))
prepared_rgba.save(INPUTS/'foreground_rgba.png')

# TripoSR requires RGB; Hunyuan consumes RGBA. Save both deliberately.
gray = Image.new('RGBA', prepared_rgba.size, (127, 127, 127, 255))
prepared_rgb = Image.alpha_composite(gray, prepared_rgba).convert('RGB')
prepared_rgb.save(INPUTS/'foreground_rgb.png')

print('RGBA image:', prepared_rgba.mode, prepared_rgba.size)
print('RGB image:', prepared_rgb.mode, prepared_rgb.size)
print('Foreground bbox (original pixels):', bbox)
display(prepared_rgba, prepared_rgb)

